"""Contact perception energy for planar disk-on-disk contact (pusher vs. object).

Observation o = (y, q): y in {0, 1} is a binary contact flag and q in R^2 is the contact location. All functions
broadcast over arbitrary leading batch dimensions, so the same energy is used for belief updates (perception) and for
the expected information gain inside the planner (action).
"""

from dataclasses import dataclass

import numpy as np


@dataclass
class ContactEnergyParams:
    """Parameters of the contact observation model."""

    pusher_radius: float
    object_radius: float
    sigma_gap: float = 0.02
    sigma_contact: float = 0.03
    p_outlier: float = 0.05
    contact_tol: float = 0.005
    """Gap below which a hypothesis is predicted to be in contact."""
    mismatch_energy: float = 5.0
    """Energy for predicting contact when none was observed (before the outlier mixture caps it)."""


def predicted_contact(
    pusher_xy: np.ndarray, object_xy: np.ndarray, params: ContactEnergyParams
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Noise-free predicted contact observation for hypothesized object positions.

    Args:
        pusher_xy: Pusher center(s), shape (..., 2).
        object_xy: Object center(s), shape (..., 2).
        params: Contact energy parameters.

    Returns:
        y_hat: Predicted contact flag (float 0/1), shape (...).
        q_hat: Predicted contact point on the pusher surface, shape (..., 2).
        gap: Signed distance between the two disks (negative = penetration), shape (...).
    """
    delta = object_xy - pusher_xy
    dist = np.linalg.norm(delta, axis=-1)
    direction = delta / np.maximum(dist, 1e-9)[..., None]
    gap = dist - (params.pusher_radius + params.object_radius)
    q_hat = pusher_xy + params.pusher_radius * direction
    y_hat = (gap <= params.contact_tol).astype(float)
    return y_hat, q_hat, gap


def contact_energy(
    obs_y: np.ndarray,
    obs_q: np.ndarray,
    pusher_xy: np.ndarray,
    object_xy: np.ndarray,
    params: ContactEnergyParams,
) -> np.ndarray:
    """Contact energy E(object_xy; o) with a constant-outlier mixture (lower = more consistent).

    * y = 0 (no contact): penalize hypotheses predicted to touch the pusher, mismatch_energy * 1[gap <= tol]
      + max(0, -gap)^2 / (2 sigma_gap^2). This is what makes a miss informative: it removes hypotheses the pusher
      swept through (which the dynamics would otherwise just push aside).
    * y = 1 (contact): gap^2 / (2 sigma_gap^2) + ||q - q_hat||^2 / (2 sigma_contact^2), i.e. the single-contact form
      of the Chamfer contact energy.

    Args:
        obs_y: Observed contact flags, shape broadcastable to (...).
        obs_q: Observed contact points, shape broadcastable to (..., 2).
        pusher_xy: Pusher center(s), shape (..., 2).
        object_xy: Hypothesized object center(s), shape (..., 2).
        params: Contact energy parameters.

    Returns:
        Energy, shape (...).
    """
    y_hat, q_hat, gap = predicted_contact(pusher_xy, object_xy, params)
    e_free = params.mismatch_energy * y_hat + np.square(np.maximum(0.0, -gap)) / (2 * params.sigma_gap**2)
    e_contact = np.square(gap) / (2 * params.sigma_gap**2) + np.square(obs_q - q_hat).sum(-1) / (
        2 * params.sigma_contact**2
    )
    energy = np.where(np.asarray(obs_y) > 0.5, e_contact, e_free)
    # -log((1 - p_out) exp(-E) + p_out), computed stably.
    p_out = params.p_outlier
    return -np.logaddexp(np.log1p(-p_out) - energy, np.log(p_out))


def expected_info_gain(
    pusher_traj: np.ndarray,
    object_traj: np.ndarray,
    weights: np.ndarray,
    params: ContactEnergyParams,
) -> np.ndarray:
    """Monte Carlo expected information gain (negative information energy) for candidate action sequences.

    For every action sequence k, each belief particle m is treated in turn as the hypothetical ground truth; its
    predicted (noise-free) contact observations along the rollout re-weight all particles via the contact energy, and
    the KL divergence between the hypothetical posterior and the prior weights is averaged over m.

    Args:
        pusher_traj: Pusher positions, shape (K, M, T, 2), one rollout per (action sequence, particle).
        object_traj: Object positions, shape (K, M, T, 2).
        weights: Prior weights of the M particles, shape (M,).
        params: Contact energy parameters.

    Returns:
        Expected information gain per action sequence, shape (K,). Non-negative.
    """
    y_hat, q_hat, _ = predicted_contact(pusher_traj, object_traj, params)  # (K, M, T), (K, M, T, 2)
    # Energy of particle i (axis 2) under observations generated by hypothetical truth m (axis 1): (K, M, M, T).
    energy = contact_energy(
        y_hat[:, :, None],
        q_hat[:, :, None],
        pusher_traj[:, None],
        object_traj[:, None],
        params,
    ).sum(-1)
    log_w = np.log(np.maximum(weights, 1e-300))
    log_post = log_w - energy
    log_post = log_post - np.logaddexp.reduce(log_post, axis=-1, keepdims=True)
    kl = (np.exp(log_post) * (log_post - log_w)).sum(-1)  # (K, M)
    return (kl * weights).sum(-1)
