"""Motion-prediction energy for beliefs over dynamics parameters, and the matching expected information gain.

A hypothesis (e.g. a centre-of-mass offset) predicts how the object moves. Its energy is the mismatch between the
predicted and the observed object features (positions first, then velocities), with the same constant-outlier mixture
as the contact energy. The same function scores hypotheses in the filter (one-step predictions vs. noisy
observations) and inside the planner's expected information gain (whole predicted trajectories vs. each other).
"""

from dataclasses import dataclass

import numpy as np


@dataclass
class DynamicsEnergyParams:
    """Parameters of the motion-prediction energy."""

    num_pos: int
    """The first `num_pos` features are positions (compared with sigma_pos), the rest velocities (sigma_vel)."""
    sigma_pos: float = 0.005
    sigma_vel: float = 0.05
    p_outlier: float = 0.05


def dynamics_energy(obs: np.ndarray, pred: np.ndarray, params: DynamicsEnergyParams) -> np.ndarray:
    """Energy of predicted features given observed features (lower = more consistent).

    E = ||d_pos||^2 / (2 sigma_pos^2) + ||d_vel||^2 / (2 sigma_vel^2), passed through -log((1 - p) exp(-E) + p) so a
    single observation can only move the belief by a bounded amount.

    Args:
        obs: Observed features, shape broadcastable to (..., F).
        pred: Predicted features, shape broadcastable to (..., F).
        params: Energy parameters.

    Returns:
        Energy, shape (...).
    """
    diff = np.asarray(obs) - np.asarray(pred)
    n = params.num_pos
    energy = np.square(diff[..., :n]).sum(-1) / (2 * params.sigma_pos**2) + np.square(diff[..., n:]).sum(-1) / (
        2 * params.sigma_vel**2
    )
    p_out = params.p_outlier
    return -np.logaddexp(np.log1p(-p_out) - energy, np.log(p_out))


def info_gain_from_energy(energy: np.ndarray, weights: np.ndarray) -> np.ndarray:
    """Expected KL between hypothetical posteriors and the prior weights.

    Args:
        energy: Energy of particle i (last axis) under the observations generated by hypothetical truth m (second to
            last axis), shape (K, M, M).
        weights: Prior weights of the M particles, shape (M,).

    Returns:
        Expected information gain per action sequence, shape (K,).
    """
    log_w = np.log(np.maximum(weights, 1e-300))
    log_post = log_w - energy
    log_post = log_post - np.logaddexp.reduce(log_post, axis=-1, keepdims=True)
    kl = (np.exp(log_post) * (log_post - log_w)).sum(-1)  # (K, M)
    return (kl * weights).sum(-1)


def expected_info_gain_dynamics(features: np.ndarray, weights: np.ndarray, params: DynamicsEnergyParams) -> np.ndarray:
    """Monte Carlo expected information gain for candidate action sequences under a parameter belief.

    For every action sequence k, each particle m is treated in turn as the true parameter: its predicted (noise-free)
    trajectory plays the role of the observations, every particle i is scored by the energy of its own predicted
    trajectory against it, and the KL between the resulting posterior and the prior weights is averaged over m.

    Args:
        features: Predicted object features, shape (K, M, T, F), one rollout per (action sequence, particle).
        weights: Prior weights of the M particles, shape (M,).
        params: Energy parameters.

    Returns:
        Expected information gain per action sequence, shape (K,). Non-negative.
    """
    # (K, M_truth, M_particle, T) -> summed over time
    energy = dynamics_energy(features[:, :, None], features[:, None], params).sum(-1)
    return info_gain_from_energy(energy, weights)
